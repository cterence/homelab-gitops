// fuzzParse parses a dump and records everything the parser emitted.
func fuzzParse(data string) (*dump, []collected, error) {
	var rows []collected

	parsed, err := parseDump(strings.NewReader(data), func(tbl *table, cols []string, row []string) error {
		rows = append(rows, collected{table: tbl.name, cols: cols, row: row})

		return nil
	})

	return parsed, rows, err
}

// fuzzFingerprint renders a parse result so two runs can be compared.
func fuzzFingerprint(parsed *dump, rows []collected) string {
	var b strings.Builder

	if parsed != nil {
		for _, tbl := range parsed.tables {
			fmt.Fprintf(&b, "T %s %s pk=%v uq=%v checks=%v idx=%v cols=", tbl.name, tbl.types(), tbl.pk, tbl.unique, tbl.checks, tbl.indexes)

			for _, c := range tbl.cols {
				fmt.Fprintf(&b, "%s:%s:%s:%t;", c.name, c.pgType, c.sqlType, c.notNull)
			}

			b.WriteByte('\n')
		}
	}

	for _, r := range rows {
		fmt.Fprintf(&b, "R %s %v\n", r.table, r.row)
	}

	return b.String()
}

// types lists the column types of a table, for the parser fingerprint.
func (t *table) types() string {
	out := make([]string, len(t.cols))
	for i, c := range t.cols {
		out[i] = c.sqlType
	}

	return strings.Join(out, ",")
}

func fuzzDB(t *testing.T) *sql.DB {
	t.Helper()

	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		t.Fatalf("opening in-memory sqlite: %v", err)
	}

	t.Cleanup(func() { _ = db.Close() })

	return db
}

// FuzzParseDump asserts the parser is deterministic and that whatever it claims
// to have parsed is internally consistent.
func FuzzParseDump(f *testing.F) {
	for _, seed := range fuzzSeeds {
		f.Add(seed)
	}

	f.Fuzz(func(t *testing.T, data string) {
		if len(data) > maxFuzzParseBytes {
			t.Skip()
		}

		first, rows, firstErr := fuzzParse(data)
		second, rowsAgain, secondErr := fuzzParse(data)

		if fmt.Sprint(firstErr) != fmt.Sprint(secondErr) {
			t.Fatalf("parse errors differ between runs: %v then %v", firstErr, secondErr)
		}

		if a, b := fuzzFingerprint(first, rows), fuzzFingerprint(second, rowsAgain); a != b {
			t.Fatalf("parse is not deterministic:\nfirst:\n%s\nsecond:\n%s", a, b)
		}

		seen := map[string]bool{}

		if first != nil {
			for _, tbl := range first.tables {
				if tbl.name == "" || len(tbl.cols) == 0 {
					t.Fatalf("table %q has no columns", tbl.name)
				}

				if seen[tbl.name] {
					t.Fatalf("table %q parsed twice", tbl.name)
				}

				seen[tbl.name] = true
			}
		}

		for _, r := range rows {
			if len(r.row) != len(r.cols) {
				t.Fatalf("row for %q has %d values for %d columns: %v", r.table, len(r.row), len(r.cols), r.row)
			}
		}
	})
}

// FuzzConvert asserts the whole pipeline never panics, never loses a row it
// parsed, and always reports what actually landed in the database.
func FuzzConvert(f *testing.F) {
	for _, seed := range fuzzSeeds {
		f.Add(seed)
	}

	f.Fuzz(func(t *testing.T, data string) {
		if len(data) > maxFuzzConvertBytes {
			t.Skip()
		}

		ctx := context.Background()
		_, rows, _ := fuzzParse(data)

		db := fuzzDB(t)

		res, err := convert(ctx, bytes.NewReader([]byte(data)), db, false, nil)
		if err != nil {
			return
		}

		want := map[string]int{}
		for _, r := range rows {
			want[r.table]++
		}

		got := map[string]int{}
		for _, c := range res.tables {
			got[c.table] = c.rows
		}

		for name, n := range want {
			if got[name] != n {
				t.Fatalf("table %q: parsed %d rows, converted %d", name, n, got[name])
			}
		}

		for name, n := range got {
			if n != 0 && want[name] != n {
				t.Fatalf("table %q: converted %d rows the parser never read", name, n)
			}
		}

		if res.rows != len(rows) {
			t.Fatalf("reported %d rows, parsed %d", res.rows, len(rows))
		}

		for name, n := range got {
			var stored int
			if err := db.QueryRow(`SELECT count(*) FROM "` + strings.ReplaceAll(name, `"`, `""`) + `"`).Scan(&stored); err != nil {
				t.Fatalf("counting rows in %q: %v", name, err)
			}

			if stored != n {
				t.Fatalf("table %q reports %d rows but holds %d", name, n, stored)
			}
		}

		again := fuzzDB(t)

		resAgain, err := convert(ctx, bytes.NewReader([]byte(data)), again, false, nil)
		if err != nil {
			t.Fatalf("second convert failed: %v", err)
		}

		if resAgain.rows != res.rows {
			t.Fatalf("convert is not deterministic: %d rows then %d", res.rows, resAgain.rows)
		}
	})
}
